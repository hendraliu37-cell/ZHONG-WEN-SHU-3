TONE_MARKS = {1:"āēīōūǖ",2:"áéíóúǘ",3:"ǎěǐǒǔǚ",4:"àèìòùǜ"}
def first_tone(py):
    seg = (py.split() or [""])[0]
    for ch in seg:
        for t, marks in TONE_MARKS.items():
            if ch in marks: return t
    return 5

